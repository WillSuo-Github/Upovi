#!/usr/bin/env python3
"""Validate reviewed identities and generate the compiled catalog; --live checks public Homebrew metadata.

No installed inventory or private preferences are read or uploaded. Public catalog facts are
identity references, not archive authenticity: production signature/version/Gatekeeper checks remain mandatory.
"""
import argparse
import datetime
import json
import pathlib
import re
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent


def entries():
    data = json.loads((ROOT / 'Resources/ReviewedSources.json').read_text())
    assert data['schemaVersion'] == 1
    seen = set()
    for item in data['entries']:
        bundle, token, app = item['bundleID'], item['cask'], item['application']
        assert re.fullmatch(r'[A-Za-z0-9_-]+(?:\.[A-Za-z0-9_-]+)+', bundle)
        assert bundle not in seen, f'Duplicate identity: {bundle}'
        seen.add(bundle)
        assert re.fullmatch(r'[a-z0-9][a-z0-9-]*', token)
        assert app.endswith('.app') and '/' not in app and '..' not in app
        url = urllib.parse.urlsplit(item['homepage'])
        assert url.scheme == 'https' and url.hostname and not url.username and not url.password and not url.query
        datetime.date.fromisoformat(item['reviewedAt'])
        for prefix in item.get('replaceBrokenElectronForVersionPrefixes', []):
            assert re.fullmatch(r'\d+\.', prefix)
    return sorted(data['entries'], key=lambda x: x['bundleID'])


def generated(items):
    lines = ['// Generated by script/review_source_catalog.py from Resources/ReviewedSources.json.',
             '// Compiled into the signed app; remote metadata cannot add identities or relax installation checks.',
             'import Foundation', '', 'public enum ReviewedSourceCatalog {',
             '    public static let casks: [String: String] = [']
    lines += [f'        {json.dumps(x["bundleID"])}: {json.dumps(x["cask"])},' for x in items]
    lines += ['    ]', '    public static func replacesBrokenElectron(for app: InstalledApp) -> Bool {',
              '        switch app.bundleID {']
    for item in items:
        prefixes = item.get('replaceBrokenElectronForVersionPrefixes', [])
        if prefixes:
            condition = ' || '.join(f'app.version.hasPrefix({json.dumps(p)})' for p in prefixes)
            lines.append(f'        case {json.dumps(item["bundleID"])}: return {condition}')
    lines += ['        default: return false', '        }', '    }', '}', '']
    return '\n'.join(lines)


def live(items):
    def strings(value):
        if isinstance(value, str):
            yield value
        elif isinstance(value, list):
            for entry in value:
                yield from strings(entry)
        elif isinstance(value, dict):
            for entry in value.values():
                yield from strings(entry)

    for item in items:
        token = item['cask']
        with urllib.request.urlopen(f'https://formulae.brew.sh/api/cask/{token}.json', timeout=30) as response:
            data = json.load(response)
        assert data['token'] == token and not data.get('disabled'), f'Unavailable cask: {token}'
        artifacts = data.get('artifacts', [])
        assert any(item['application'] in a.get('app', []) for a in artifacts), f'Application identity changed: {token}'
        references = set(strings(artifacts))
        # Reviewed casks may declare identity only in an exact cache/preferences path.
        # Never accept a substring, extension bundle, or glob as the main bundle identity.
        references |= {pathlib.PurePosixPath(value).name for value in tuple(references)}
        identities = {item['bundleID'], item['bundleID'] + '.plist', item['bundleID'] + '.savedState'}
        assert references & identities, f'Bundle identity reference missing: {token}'
        print(f'{token}: identity metadata matched; source version {data["version"]}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--live', action='store_true')
    options = parser.parse_args()
    items = entries()
    path = ROOT / 'Sources/UpoviCore/Services/ReviewedSourceCatalog.swift'
    text = generated(items)
    if options.write:
        path.write_text(text)
    else:
        assert path.read_text() == text, 'Regenerate the compiled catalog with --write'
    if options.live:
        live(items)
    print(f'{len(items)} reviewed identities validated')


if __name__ == '__main__':
    main()
